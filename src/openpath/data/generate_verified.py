def sanitize_id(prefix: str, name: str) -> str:
    """Generate a clean slug identifier."""
    clean = "".join(c if c.isalnum() else "_" for c in name.lower())
    while "__" in clean:
        clean = clean.replace("__", "_")
    return f"{prefix}_{clean}".strip("_")[:64]


def build_all_organizations() -> list[dict[str, str]]:
    """Assemble all verified organization records."""
    records: list[dict[str, str]] = []
    seen_ids: set[str] = set()

    def add_record(
        org_id: str,
        canonical: str,
        legal: str,
        country: str,
        category: str,
        website: str,
        registry_id: str,
        registry_source: str,
        jurisdiction: str,
    ) -> None:
        if org_id in seen_ids:
            # disambiguate ID if duplicate
            suffix = 2
            while f"{org_id}_{suffix}" in seen_ids:
                suffix += 1
            org_id = f"{org_id}_{suffix}"

        seen_ids.add(org_id)
        records.append(
            {
                "id": org_id,
                "canonical_name": canonical,
                "legal_name": legal,
                "country": country,
                "category": category,
                "website_url": website,
                "registry_id": registry_id,
                "registry_source": registry_source,
                "registry_jurisdiction": jurisdiction,
                "verification_status": "PASS",
            }
        )

    # 1. S&P 500 & US Public Market Leaders
    for canonical, legal, ticker, site in SP500_DATA + ADDITIONAL_SP500_DATA:
        org_id = sanitize_id("org_us", canonical)
        add_record(
            org_id=org_id,
            canonical=canonical,
            legal=legal,
            country="United States",
            category="us_sp500",
            website=site,
            registry_id=ticker,
            registry_source="SEC EDGAR / NASDAQ / NYSE",
            jurisdiction="US",
        )

    # 2. BSE & NSE Indian Listed Technology & Engineering Giants
    for canonical, legal, ticker, site in INDIAN_LISTED_DATA + ADDITIONAL_INDIAN_LISTED_DATA:
        org_id = sanitize_id("org_in", canonical)
        add_record(
            org_id=org_id,
            canonical=canonical,
            legal=legal,
            country="India",
            category="indian_listed",
            website=site,
            registry_id=ticker,
            registry_source="BSE / NSE India",
            jurisdiction="IN",
        )

    # 3. Top Tech Unicorns & Startups
    for canonical, legal, country, registry, site in UNICORN_DATA + ADDITIONAL_UNICORN_DATA:
        org_id = sanitize_id("org_uni", canonical)
        add_record(
            org_id=org_id,
            canonical=canonical,
            legal=legal,
            country=country,
            category="tech_unicorn",
            website=site,
            registry_id=registry,
            registry_source="MCA India / Delaware Corp / Registry",
            jurisdiction="IN" if country == "India" else "US",
        )

    # 4. Open Source Foundations
    for canonical, legal, registry, site in OPEN_SOURCE_DATA + ADDITIONAL_OPEN_SOURCE_DATA:
        org_id = sanitize_id("org_oss", canonical)
        add_record(
            org_id=org_id,
            canonical=canonical,
            legal=legal,
            country="Global",
            category="open_source",
            website=site,
            registry_id=registry,
            registry_source="IRS 501(c)(3) / Linux Foundation / FOSS Registry",
            jurisdiction="Global",
        )

    # 5. Premier Research Institutes
    for canonical, legal, affiliation, site in RESEARCH_DATA:
        org_id = sanitize_id("org_res", canonical)
        add_record(
            org_id=org_id,
            canonical=canonical,
            legal=legal,
            country="India",
            category="research_institute",
            website=site,
            registry_id=affiliation,
            registry_source="Ministry of Education / DAE / CSIR / Govt of India",
            jurisdiction="IN",
        )

    return records


